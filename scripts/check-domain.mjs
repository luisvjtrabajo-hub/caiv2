import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
import ts from 'typescript';
const catalog=JSON.parse(fs.readFileSync('lib/catalog.json','utf8'));
const source=fs.readFileSync('lib/domain.ts','utf8').replace("import catalog from './catalog.json';",`const catalog=${JSON.stringify(catalog)};`);
const result=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}});
const checks=path.resolve('.sites-runtime/checks');fs.mkdirSync(checks,{recursive:true});fs.writeFileSync(path.join(checks,'domain.cjs'),result.outputText);
const domain=await import(pathToFileURL(path.join(checks,'domain.cjs')).href);
const now=new Date(2026,10,9,12);
assert.equal(catalog.missions.length,47);
assert.equal(new Set(catalog.missions.map(m=>m.code)).size,47);
assert.equal(catalog.missions.reduce((n,m)=>n+m.points,0),4635);
assert.equal(catalog.ranks.length,10);
assert.equal(catalog.missions.filter(m=>domain.canReport(m,4)).length,33);
assert.equal(catalog.missions.filter(m=>domain.canReport(m,1)).length,9);
assert.equal(domain.earliestMissionDate(now),'2026-10-26');
assert.ok(domain.isValidMissionDate('2026-10-26',now));
assert.ok(domain.isValidMissionDate('2026-11-09',now));
assert.equal(domain.isValidMissionDate('2026-10-25',now),false);
assert.equal(domain.isValidMissionDate('2026-11-10',now),false);
assert.equal(domain.strongestBonus(150,{first:true,quality:true,consistency:true}),30);
assert.equal(domain.strongestBonus(40,{first:true,quality:true,consistency:true}),25);
assert.ok(domain.isHonorMission('VIG-02'));
assert.equal(domain.isFieldMission('ESC-02'),true);
assert.equal(domain.isFieldMission('VIG-02'),false);
assert.equal(catalog.missions.some(m=>m.code==='PRE-02'||m.code==='FOR-03'||m.code==='FOR-01'),false);
console.log('17 comprobaciones superadas: catálogo, puntos, acceso por rango, fechas, bonos y registro de honor.');
