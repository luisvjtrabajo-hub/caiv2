import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=path=>fs.readFileSync(path,'utf8');
const home=read('app/public-home.tsx');
const member=read('app/member-workspace.tsx');
const access=read('app/ingresar/page.tsx');
const globe=read('app/mission-map.tsx');
assert.ok(read('app/page.tsx').includes("from './public-home'"));
assert.equal(home.includes('<DemoAuthGate>'),false);
assert.ok(home.includes('href="/ingresar"'));
assert.ok(home.includes('href="/ingresar?registro=1"'));
assert.ok(home.includes(' decorative/>'));
assert.ok(access.includes("window.location.replace('/miembros')"));
assert.ok(read('app/miembros/page.tsx').includes("from '../member-workspace'"));
assert.ok(member.includes("useState<View>('map')"));
assert.ok(member.includes('<DemoAuthGate><MissionWorkspace/></DemoAuthGate>'));
assert.ok(globe.includes("map.geoOrthographic()"));
assert.ok(globe.includes("map.geoNaturalEarth1()"));
assert.ok(globe.includes('decorative?[]:places.map'));
assert.ok(globe.includes('prefers-reduced-motion: reduce'));
assert.ok(globe.includes('Pausar giro del globo'));
for(const asset of ['logo-cai.png','leon-xiv.webp','hermanos.jpg','estatua-pedro.jpg'])assert.ok(fs.statSync('public/images/reference/'+asset).size>1000);
console.log('18 comprobaciones de portada y navegación superadas: portada pública, login propio, mapa tras ingresar, privacidad y globo accesible.');
