import assert from 'node:assert/strict';
import fs from 'node:fs';
import {authenticateDemo,restoreDemoSession,DEMO_SESSION_DURATION} from '../lib/demo-auth.ts';
const now=Date.UTC(2026,10,9,15);
const session=authenticateDemo('admin','CaiDemo2026!',now);
assert.ok(session);
assert.equal(session.role,'admin');
assert.equal(session.expiresAt,now+DEMO_SESSION_DURATION);
assert.equal(authenticateDemo('admin','incorrecta',now),null);
assert.equal(authenticateDemo('otro','CaiDemo2026!',now),null);
assert.equal(authenticateDemo('','',now),null);
assert.ok(authenticateDemo(' ADMIN ','CaiDemo2026!',now));
assert.deepEqual(restoreDemoSession(JSON.stringify(session),now),session);
assert.equal(restoreDemoSession(JSON.stringify(session),session.expiresAt),null);
assert.equal(restoreDemoSession('invalid-json',now),null);
assert.equal(restoreDemoSession(null,now),null);
assert.equal(restoreDemoSession(JSON.stringify({...session,role:'member'}),now),null);
assert.equal(restoreDemoSession(JSON.stringify({...session,expiresAt:now+DEMO_SESSION_DURATION+1}),now),null);
assert.equal('password' in session,false);
const page=fs.readFileSync('app/member-workspace.tsx','utf8');
assert.ok(page.includes('<DemoAuthGate><MissionWorkspace/></DemoAuthGate>'));
assert.ok(page.includes('onClick={logout}'));
const login=fs.readFileSync('app/demo-auth.tsx','utf8');
assert.ok(login.includes('sessionStorage.removeItem(DEMO_SESSION_KEY)'));
assert.equal(login.includes('signin-with-chatgpt'),false);
console.log('18 comprobaciones de acceso superadas: credenciales, sesión, caducidad, cierre de sesión y login propio.');
